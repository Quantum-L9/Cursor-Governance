# pyright: strict
"""Shared context for the contract-registry and projection-binding tooling.

One place reads a generation binding (``skills/<pack>/bindings/GOVERNANCE_GENERATION.yaml``),
its schema-aligned sources, their content digests and the pack's reference index, so the
registry generator, the projection-binding generator and the parity validator compute each of
those exactly one way. Every rule applied here is stated by that binding; this module only
executes it.
"""

from __future__ import annotations

import datetime as _dt
import importlib.util
import json
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from types import ModuleType
from typing import Any, cast

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_BINDING = Path("skills/l9-global-architect/bindings/GOVERNANCE_GENERATION.yaml")
GENERATED_HEADER = (
    "# GENERATED by {generator} from {binding}.\n"
    "# Do not edit by hand: regenerate with `make contract-registry`.\n"
)


def sibling(name: str) -> ModuleType:
    """Load ``tools/authority/<name>.py`` by path (``tools/`` is not a package)."""
    key = f"authority_{name}"
    if key in sys.modules:
        return sys.modules[key]
    path = Path(__file__).resolve().parent / f"{name}.py"
    spec = importlib.util.spec_from_file_location(key, path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"{path} is not importable")
    module = importlib.util.module_from_spec(spec)
    sys.modules[key] = module
    spec.loader.exec_module(module)
    return module


canonical = sibling("canonical_json")


class GenerationBlocked(Exception):
    """A required input, capability or resolution is unavailable; nothing may be generated."""


class GenerationRefused(Exception):
    """The inputs contradict a registration, registry or projection requirement."""


def as_map(value: Any) -> dict[str, Any]:
    return cast(dict[str, Any], value) if isinstance(value, dict) else {}


def as_list(value: Any) -> list[Any]:
    return cast(list[Any], value) if isinstance(value, list) else []


def as_maps(value: Any) -> list[dict[str, Any]]:
    return [cast(dict[str, Any], v) for v in as_list(value) if isinstance(v, dict)]


def dump_yaml(document: dict[str, Any], header: str) -> str:
    """Deterministic YAML: insertion order kept, block style, no line folding."""
    body = yaml.safe_dump(
        document, sort_keys=False, default_flow_style=False, allow_unicode=True, width=10_000
    )
    return header + body


def git(root: Path, *args: str) -> subprocess.CompletedProcess[bytes]:
    return subprocess.run(["git", "-C", str(root), *args], capture_output=True, check=False)


@dataclass(frozen=True)
class Source:
    rel: str  # repository-relative path
    pack_rel: str  # path relative to the pack root
    schema_ref: str
    document: dict[str, Any]
    digest: str


@dataclass(frozen=True)
class Context:
    root: Path
    binding_rel: str
    binding: dict[str, Any]
    pack: Path
    pack_rel: str

    # ------------------------------------------------------------------ loading

    @classmethod
    def load(cls, root: Path, binding_rel: Path = DEFAULT_BINDING) -> Context:
        path = root / binding_rel
        if not path.is_file():
            raise GenerationBlocked(f"generation binding {binding_rel} is absent")
        binding = canonical.load_yaml(path.read_text(encoding="utf-8"))
        if not isinstance(binding, dict):
            raise GenerationBlocked(f"{binding_rel} is not a mapping")
        pack = path.parent.parent
        return cls(
            root=root,
            binding_rel=binding_rel.as_posix(),
            binding=cast(dict[str, Any], binding),
            pack=pack,
            pack_rel=pack.relative_to(root).as_posix(),
        )

    def section(self, name: str) -> dict[str, Any]:
        return as_map(self.binding.get(name))

    def repo_rel(self, pack_rel: str) -> str:
        return f"{self.pack_rel}/{pack_rel}"

    def read(self, rel: str) -> bytes:
        path = self.root / rel
        if not path.is_file():
            raise GenerationBlocked(f"{rel} is absent")
        return path.read_bytes()

    # ------------------------------------------------------------------ capability

    def verify_tooling(self, *, projections: bool) -> dict[str, str]:
        tooling = self.section("tooling")
        requirement = self.section("external_tooling_requirement")
        needed = [str(n) for n in as_list(requirement.get("must_observe_all"))]
        if projections:
            needed += [
                str(n)
                for n in as_list(
                    requirement.get("projection_binding_generation_additionally_requires")
                )
            ]
        observed: dict[str, str] = {}
        for name in needed:
            ref = tooling.get(name)
            if not ref or not (self.root / str(ref)).is_file():
                raise GenerationBlocked(f"CAPABILITY_BLOCK: {name} ({ref!r}) is not present")
            observed[name] = str(ref)
        return observed

    # ------------------------------------------------------------------ sources

    def digest_of(self, document: Any) -> str:
        """``contract_digest``: semantic digest with the binding's excluded fields removed."""
        trimmed: Any = json.loads(canonical.canonical_json(document))
        for dotted in as_list(self.section("contract_digest").get("excludes")):
            node: Any = trimmed
            parts = str(dotted).split(".")
            for part in parts[:-1]:
                node = as_map(node).get(part)
            if isinstance(node, dict):
                cast(dict[str, Any], node).pop(parts[-1], None)
        return str(canonical.semantic_digest(trimmed))

    def sources(self) -> list[Source]:
        out: list[Source] = []
        for entry in as_maps(self.binding.get("schema_aligned_sources")):
            pack_rel = str(entry.get("path"))
            rel = self.repo_rel(pack_rel)
            try:
                document = canonical.load_yaml(self.read(rel).decode("utf-8"))
            except canonical.CanonicalizationError as exc:
                raise GenerationRefused(f"{rel} does not parse: {exc}") from exc
            if not isinstance(document, dict):
                raise GenerationRefused(f"{rel} is not a mapping")
            doc = cast(dict[str, Any], document)
            schema_ref = str(entry.get("schema_ref"))
            out.append(Source(rel, pack_rel, schema_ref, doc, self.digest_of(doc)))
        return out

    def schema_paths(self, schema_refs: list[str]) -> list[str]:
        root = str(self.section("schema_resolution").get("schema_root"))
        refs = set(schema_refs)
        # inheritance closure: every schema file these refs extend, as far as files exist
        queue = list(refs)
        while queue:
            ref = queue.pop()
            path = self.root / root / f"{ref}.yaml"
            if not path.is_file():
                continue
            schema = as_map(canonical.load_yaml(path.read_text(encoding="utf-8")))
            for base in as_list(as_map(schema.get("inheritance")).get("extends")):
                if str(base) not in refs:
                    refs.add(str(base))
                    queue.append(str(base))
        family_owner = [
            p.name.removesuffix(".yaml")
            for p in sorted((self.root / root).glob("canonical.schema.*.yaml"))
            if "type_registry:" in p.read_text(encoding="utf-8")
        ]
        refs.update(family_owner)
        present = [r for r in refs if (self.root / root / f"{r}.yaml").is_file()]
        return sorted(f"{root}/{r}.yaml" for r in present)

    # ------------------------------------------------------------------ reference resolution

    def pack_identities(self) -> dict[str, list[str]]:
        """``id -> [repo-relative path]`` over the pack manifest's semantic owners."""
        resolution = self.section("reference_resolution")
        manifest_rel = self.repo_rel(str(resolution.get("pack_manifest")))
        manifest = as_map(canonical.load_yaml(self.read(manifest_rel).decode("utf-8")))
        owners = sorted(
            {str(as_map(v).get("owner")) for v in as_map(manifest.get("semantic_owners")).values()}
        )
        index: dict[str, list[str]] = {}
        for owner in owners:
            rel = self.repo_rel(owner)
            if not (self.root / rel).is_file():
                continue
            document = as_map(canonical.load_yaml(self.read(rel).decode("utf-8")))
            if not document:
                continue
            first = as_map(next(iter(document.values())))
            for key, value in first.items():
                if key.endswith("_id") and isinstance(value, str):
                    index.setdefault(value, []).append(rel)
        return index

    def manifest_semantic_owner_paths(self) -> set[str]:
        resolution = self.section("reference_resolution")
        manifest_rel = self.repo_rel(str(resolution.get("pack_manifest")))
        manifest = as_map(canonical.load_yaml(self.read(manifest_rel).decode("utf-8")))
        return {
            self.repo_rel(str(as_map(v).get("owner")))
            for v in as_map(manifest.get("semantic_owners")).values()
        }

    # ------------------------------------------------------------------ provenance

    def generation_inputs(self, sources: list[Source], external_refs: list[str]) -> list[str]:
        spec = self.section("generation_inputs")
        paths = {self.repo_rel(str(p)) for p in as_list(spec.get("pack_paths"))}
        if spec.get("includes_schema_aligned_sources"):
            paths.update(s.rel for s in sources)
        if spec.get("includes_reference_resolution_targets"):
            paths.update(external_refs)
        if spec.get("includes_used_schemas"):
            refs = [s.schema_ref for s in sources]
            output = self.section("contract_registry_output")
            projection = self.section("projection_binding_generation")
            refs += [str(output.get("schema_ref")), str(projection.get("schema_ref"))]
            paths.update(self.schema_paths(refs))
        return sorted(paths)

    def head_metadata(self, inputs: list[str]) -> dict[str, str]:
        """``source_commit_sha`` and ``generated_at`` from HEAD, refusing dirty inputs."""
        status = git(self.root, "status", "--porcelain", "--", *inputs)
        if status.returncode != 0:
            raise GenerationBlocked(f"git status failed: {status.stderr.decode(errors='replace')}")
        if status.stdout.strip():
            dirty = status.stdout.decode(errors="replace").strip()
            raise GenerationBlocked(
                f"generation inputs are not committed at HEAD; commit them first:\n{dirty}"
            )
        head = git(self.root, "rev-parse", "HEAD")
        if head.returncode != 0:
            raise GenerationBlocked("no HEAD commit")
        sha = head.stdout.decode().strip()
        return {"source_commit_sha": sha, "generated_at": self.commit_time(sha)}

    def commit_time(self, sha: str) -> str:
        shown = git(self.root, "show", "-s", "--format=%ct", sha)
        if shown.returncode != 0:
            raise GenerationBlocked(f"commit {sha} is not available")
        stamp = _dt.datetime.fromtimestamp(int(shown.stdout.decode().strip()), tz=_dt.UTC)
        return stamp.strftime("%Y-%m-%dT%H:%M:%SZ")

    def verify_provenance(self, metadata: dict[str, Any], inputs: list[str]) -> list[str]:
        """Problems with the recorded commit; raises ``GenerationBlocked`` if it is absent."""
        sha = str(metadata.get("source_commit_sha"))
        if git(self.root, "cat-file", "-e", f"{sha}^{{commit}}").returncode != 0:
            raise GenerationBlocked(
                f"provenance unverifiable: commit {sha} is not in this clone (shallow history?)"
            )
        problems: list[str] = []
        if self.commit_time(sha) != metadata.get("generated_at"):
            problems.append(f"generated_at {metadata.get('generated_at')} is not {sha}'s time")
        for rel in inputs:
            shown = git(self.root, "show", f"{sha}:{rel}")
            if shown.returncode != 0:
                problems.append(f"{rel} is absent at {sha}")
            elif shown.stdout != self.read(rel):
                problems.append(f"{rel} differs from its bytes at {sha}")
        return problems
