"""Deliver end-session handoffs to their owners without touching the PR's git tree.

The post-publish Stop hooks used to commit both handoffs onto the PR head and
push them. That moved the head after CI had started, added files to PRs whose
contract allowed none, and left the governance handoff in whichever repository
was published, where its owner never read it.

Delivery now goes where each handoff belongs:

- the **session handoff** (the in-scope repository's) is one PR comment, edited
  in place on every later publication of the same PR;
- the **governance handoff** (Cursor-Governance's) goes to a friction intake in
  Cursor-Governance: one open issue per friction id, one comment per session
  that met it. When the intake cannot be reached it falls back to a PR comment,
  and the result says so.

Nothing here commits, pushes, or writes inside the work tree. A local copy is
kept under the git directory. Every GitHub call goes through ``gh api`` (REST;
the sanctioned transport on model-controlled surfaces) and a failure is
returned, never raised: the callers are fail-open Stop hooks.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Protocol

#: Override for the intake repository (tests, a fork). Default: Cursor-Governance.
INTAKE_ENV = "L9_FRICTION_INTAKE_REPO"
#: Per REST call; the callers are Stop hooks with 60-90 s budgets.
TIMEOUT_S = float(os.environ.get("L9_REPORT_GIT_TIMEOUT") or 20)
PER_PAGE = 100
MAX_PAGES = 10
FRICTION_TITLE_PREFIX = "[session-friction]"
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n"
LOCAL_DIR = Path("l9-reports") / "end-session"

_FRICTION_ID = re.compile(r"<!-- l9-friction-id:([a-z0-9-]+) -->")


class TransportError(RuntimeError):
    """A GitHub call failed; the message says how."""


#: What a delivery step may raise: transport failures, a REST payload missing a
#: field it must carry, or the intake identity's owner failing to import.
DELIVERY_ERRORS = (TransportError, KeyError, TypeError, ValueError, ImportError)


class Transport(Protocol):
    def request(self, method: str, path: str, body: dict[str, Any] | None = None) -> Any: ...


class GhApi:
    """``gh api`` over REST. Raises TransportError, never anything else."""

    def __init__(self, gh: str | None = None, timeout: float = TIMEOUT_S) -> None:
        self.gh = gh
        self.timeout = timeout

    def request(self, method: str, path: str, body: dict[str, Any] | None = None) -> Any:
        gh = self.gh or shutil.which("gh")
        if not gh:
            raise TransportError("gh is not installed")
        argv = [gh, "api", "--method", method, path]
        if body is not None:
            argv += ["--input", "-"]
        try:
            proc = subprocess.run(
                argv,
                input=json.dumps(body) if body is not None else None,
                capture_output=True,
                text=True,
                timeout=self.timeout,
                check=False,
            )
        except (OSError, subprocess.TimeoutExpired) as exc:
            raise TransportError(f"{type(exc).__name__}: {str(exc)[:160]}") from exc
        if proc.returncode != 0:
            reason = (proc.stderr or proc.stdout or f"exit {proc.returncode}").strip()
            raise TransportError(f"{method} {path}: {reason.splitlines()[-1][:200]}")
        try:
            return json.loads(proc.stdout) if proc.stdout.strip() else None
        except json.JSONDecodeError as exc:
            raise TransportError(f"{method} {path}: unparseable response") from exc


def get_all(transport: Transport, path: str) -> list[dict[str, Any]]:
    """Every item of a paginated REST list, bounded at ``MAX_PAGES`` pages."""
    joiner = "&" if "?" in path else "?"
    items: list[dict[str, Any]] = []
    for page in range(1, MAX_PAGES + 1):
        batch = transport.request("GET", f"{path}{joiner}per_page={PER_PAGE}&page={page}")
        if not isinstance(batch, list):
            raise TransportError(f"GET {path}: expected a list")
        items.extend(item for item in batch if isinstance(item, dict))
        if len(batch) < PER_PAGE:
            break
    return items


@dataclass(frozen=True)
class Delivery:
    status: str  # delivered | fallback | written | failed
    detail: str = ""
    urls: tuple[str, ...] = field(default_factory=tuple)


# --- Local copy ------------------------------------------------------------------


def local_copy_dir(root: Path, kind: str) -> Path:
    """``<git dir>/l9-reports/end-session/<kind>``: never part of the work tree.

    Outside a git work tree there is no PR to protect, so ``<root>/.l9/reports``
    is used instead.
    """
    root = Path(root)
    try:
        proc = subprocess.run(
            ["git", "-C", str(root), "rev-parse", "--git-path", str(LOCAL_DIR / kind)],
            capture_output=True,
            text=True,
            timeout=TIMEOUT_S,
            check=False,
        )
        rel = proc.stdout.strip() if proc.returncode == 0 else ""
    except (OSError, subprocess.TimeoutExpired):
        rel = ""
    path = Path(rel) if rel else Path(".l9") / "reports" / "end-session" / kind
    path = path if path.is_absolute() else root / path
    path.mkdir(parents=True, exist_ok=True)
    return path


def write_local_copy(root: Path, kind: str, filename: str, text: str) -> Path:
    if Path(filename).name != filename or not filename.endswith(".md"):
        raise ValueError(f"handoff filename must be a bare *.md name, got {filename!r}")
    path = local_copy_dir(root, kind) / filename
    path.write_text(text, encoding="utf-8")
    return path


# --- PR comment ------------------------------------------------------------------


def pr_comment_marker(kind: str, repo: str, number: int) -> str:
    """One marker per (handoff kind, PR): never matches a human comment or the other kind."""
    return f"<!-- l9-handoff:{kind}:{repo.lower()}#{int(number)} -->"


def defang(text: str) -> str:
    """Agent text cannot forge a marker this module keys on."""
    return text.replace("<!--", "&lt;!--")


def upsert_pr_comment(transport: Transport, repo: str, number: int, marker: str, body: str) -> str:
    """Create or edit the one comment carrying ``marker``; return its URL."""
    text = f"{marker}\n{defang(body).rstrip()}{FOOTER}"
    comments = get_all(transport, f"repos/{repo}/issues/{int(number)}/comments")
    mine = [c for c in comments if marker in str(c.get("body") or "")]
    if mine:
        current = mine[0]
        if str(current.get("body") or "") != text:
            current = transport.request(
                "PATCH", f"repos/{repo}/issues/comments/{current['id']}", {"body": text}
            )
        return str((current or {}).get("html_url") or "")
    created = transport.request(
        "POST", f"repos/{repo}/issues/{int(number)}/comments", {"body": text}
    )
    return str((created or {}).get("html_url") or "")


# --- Friction intake ---------------------------------------------------------------


def intake_repository() -> str:
    """The friction intake: ``L9_FRICTION_INTAKE_REPO``, else Cursor-Governance."""
    explicit = os.environ.get(INTAKE_ENV, "").strip()
    if explicit:
        return explicit
    from ops.autonomy.session_debt import GOVERNANCE_REPOSITORY  # noqa: PLC0415 - one owner

    return GOVERNANCE_REPOSITORY


def normalize_friction_id(raw: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", str(raw).lower()).strip("-")[:80].strip("-")
    return slug or "unnamed"


def friction_items(brief: dict[str, Any] | None) -> list[dict[str, str]]:
    """The governance brief as intake items: friction, blockers and governance actions.

    Each item carries the brief's own words. Workarounds are joined onto the
    friction item they name. Degraded bootstrap is left to the memory record:
    it is observed per session, not a defect with an owner to close.
    """
    if not brief:
        return []
    workarounds = {
        normalize_friction_id(w.get("item", "")): str(w.get("workaround") or "")
        for w in brief.get("workarounds") or []
        if isinstance(w, dict)
    }
    items: list[dict[str, str]] = []
    for entry in brief.get("environment_friction") or []:
        if not isinstance(entry, dict) or not str(entry.get("item") or "").strip():
            continue
        fid = normalize_friction_id(entry["item"])
        items.append(
            {
                "id": fid,
                "section": "environment friction",
                "detail": str(entry.get("detail") or ""),
                "impact": str(entry.get("impact") or ""),
                "workaround": workarounds.get(fid, ""),
            }
        )
    for entry in brief.get("blockers") or []:
        if isinstance(entry, dict) and str(entry.get("item") or "").strip():
            items.append(
                {
                    "id": normalize_friction_id(entry["item"]),
                    "section": "blocker",
                    "detail": str(entry.get("blocker") or ""),
                    "workaround": str(entry.get("unblock") or ""),
                }
            )
    for entry in brief.get("governance_actions") or []:
        if isinstance(entry, dict) and str(entry.get("action") or "").strip():
            items.append(
                {
                    "id": normalize_friction_id(entry["action"]),
                    "section": "governance action",
                    "detail": " — ".join(
                        str(entry.get(k) or "") for k in ("action", "where", "why") if entry.get(k)
                    ),
                }
            )
    return items


def _occurrence_lines(item: dict[str, str], occurrence: dict[str, str]) -> list[str]:
    lines = [
        f"**{item.get('section') or 'friction'}** in {occurrence.get('label') or '?'}",
        "",
    ]
    for key, label in (
        ("url", "PR"),
        ("session_id", "Session"),
        ("agent_id", "Agent"),
    ):
        if occurrence.get(key):
            lines.append(f"- {label}: {occurrence[key]}")
    for key, label in (
        ("detail", "Detail"),
        ("impact", "Impact"),
        ("workaround", "Workaround"),
    ):
        if item.get(key):
            lines.append(f"- {label}: {item[key]}")
    return lines


def deliver_friction(
    transport: Transport,
    items: Sequence[dict[str, str]],
    occurrence: dict[str, str],
    *,
    intake: str | None = None,
) -> list[str]:
    """Record each item on its intake issue; return the issue URLs.

    One open issue per normalized friction id, found by its body marker (labels
    are not relied on: GitHub drops them without push access). One comment per
    session per issue, so the ledger repeating an item across a session's
    briefs does not inflate the count.
    """
    repo = intake or intake_repository()
    issues: dict[str, dict[str, Any]] = {}
    for issue in get_all(transport, f"repos/{repo}/issues?state=open"):
        if "pull_request" in issue:  # GitHub marks a PR by the key, not its value
            continue
        match = _FRICTION_ID.search(str(issue.get("body") or ""))
        if match:
            issues.setdefault(match.group(1), issue)
    who = occurrence.get("session_id") or occurrence.get("label") or "unknown"
    urls: list[str] = []
    for item in items:
        fid = normalize_friction_id(item.get("id", ""))
        issue = issues.get(fid)
        if issue is None:
            body = (
                f"<!-- l9-friction-id:{fid} -->\n"
                f"Agent sessions reported `{fid}` in their governance handoff "
                "(`l9.governance_handoff.v1`). Each comment below is one session "
                "that met it. Close this issue when the cause is fixed; a later "
                "report opens a new one."
            )
            issue = transport.request(
                "POST",
                f"repos/{repo}/issues",
                {"title": f"{FRICTION_TITLE_PREFIX} {fid}", "body": body + FOOTER},
            )
            if not isinstance(issue, dict) or "number" not in issue:
                raise TransportError(f"POST repos/{repo}/issues: no issue returned")
            issues[fid] = issue
        marker = f"<!-- l9-friction-occurrence:{fid}:{normalize_friction_id(who)} -->"
        number = int(issue["number"])
        seen = get_all(transport, f"repos/{repo}/issues/{number}/comments")
        if not any(marker in str(c.get("body") or "") for c in seen):
            text = "\n".join(_occurrence_lines(item, occurrence))
            transport.request(
                "POST",
                f"repos/{repo}/issues/{number}/comments",
                {"body": f"{marker}\n{defang(text)}{FOOTER}"},
            )
        urls.append(str(issue.get("html_url") or f"{repo}#{number}"))
    return list(dict.fromkeys(urls))


# --- One handoff -------------------------------------------------------------------


def deliver(
    kind: str,
    pub: dict[str, Any],
    text: str,
    *,
    friction: Iterable[dict[str, str]] | None = None,
    session_id: str = "",
    agent_id: str = "",
    transport: Transport | None = None,
) -> Delivery:
    """Deliver one rendered handoff. Never raises; the result says what happened."""
    transport = transport or GhApi()
    repo = str(pub.get("repo") or "")
    number = int(pub.get("number") or 0)
    marker = pr_comment_marker(kind, repo, number)
    if kind == "governance-handoff":
        items = list(friction or [])
        if not items:
            return Delivery("written", "no friction items to deliver; memory record and local copy")
        occurrence = {
            "label": str(pub.get("label") or f"{repo}#{number}"),
            "url": str(pub.get("url") or ""),
            "session_id": session_id,
            "agent_id": agent_id,
        }
        try:
            urls = deliver_friction(transport, items, occurrence)
            return Delivery(
                "delivered", f"{len(items)} item(s) to the friction intake", tuple(urls)
            )
        except DELIVERY_ERRORS as exc:
            intake_error = (
                f"{type(exc).__name__}: {exc}" if not isinstance(exc, TransportError) else str(exc)
            )
        if not repo or not number:
            return Delivery(
                "failed", f"friction intake unreachable ({intake_error}); no PR to fall back to"
            )
        try:
            url = upsert_pr_comment(transport, repo, number, marker, text)
        except DELIVERY_ERRORS as exc:
            return Delivery(
                "failed", f"friction intake unreachable ({intake_error}); PR comment failed ({exc})"
            )
        return Delivery(
            "fallback", f"friction intake unreachable ({intake_error}); posted on the PR", (url,)
        )
    if not repo or not number:
        return Delivery("failed", "no publication repository/number to comment on")
    try:
        url = upsert_pr_comment(transport, repo, number, marker, text)
    except DELIVERY_ERRORS as exc:
        return Delivery("failed", f"PR comment failed ({exc})")
    return Delivery("delivered", "PR comment", (url,))
