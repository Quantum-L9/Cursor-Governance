"""#872: the issue-comment helper accepts ordinary punctuation and signs its posts.

`_SAFE_TOKEN` rejected commas, parentheses, quotes and backticks, so a close
breadcrumb describing a real change could not be posted, and the posted body
carried no Claude Code attribution footer. Free text is widened; characters that
could break out of the HTML marker or ping a user stay refused.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import pytest

REPO = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO / "skills" / "l9-issue-remediation" / "scripts"))

import post_issue_comment as pic  # noqa: E402


@pytest.mark.parametrize(
    "text",
    [
        "fixed in PR #12, see `ops/x.py` (line 4)",
        'renamed "foo" to \'bar\'; tests green!',
        "https://github.com/o/r/pull/5 - merged [a1b2c3d]",
    ],
)
def test_free_text_accepts_ordinary_punctuation(text: str) -> None:
    assert pic._require_safe("change", text) == text


@pytest.mark.parametrize(
    "text",
    [
        "close --> <script>",
        "ping @someone",
        "two\nlines",
        "",
    ],
)
def test_free_text_still_refuses_marker_breakout_mentions_and_newlines(text: str) -> None:
    with pytest.raises(SystemExit):
        pic._require_safe("change", text)


def test_marker_fields_stay_strict() -> None:
    with pytest.raises(SystemExit):
        pic._require_marker_safe("cluster-id", "a;b")
    assert pic._require_marker_safe("cluster-id", "cg-make-pr") == "cg-make-pr"


def test_posted_body_carries_attribution_footer(monkeypatch: pytest.MonkeyPatch) -> None:
    sent: dict[str, Any] = {}

    class _Resp:
        status = 201

        def __enter__(self) -> "_Resp":
            return self

        def __exit__(self, *_: object) -> None:
            return None

    def fake_exchange(request: Any, **_: Any) -> _Resp:
        sent["data"] = request.data
        return _Resp()

    monkeypatch.setattr(pic, "https_exchange", fake_exchange)
    pic._post_comment("o", "r", 1, "## body\n", "tok")
    import json

    body = json.loads(sent["data"])["body"]
    assert body.rstrip().endswith(pic.FOOTER.strip())
    assert body.count("Generated by [Claude Code]") == 1
    # already-signed bodies are not double-signed
    pic._post_comment("o", "r", 1, body, "tok")
    assert json.loads(sent["data"])["body"].count("Generated by [Claude Code]") == 1
